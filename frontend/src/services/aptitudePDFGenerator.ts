import { aptitudeNotes } from "@/data/aptitudeNotes";
import { aptitudeFormulas } from "@/data/aptitudeFormulas";

function generateNotesMarkdown(): string {
  let content = `# Aptitude Notes\n*Generated by Interview Express*\n\n`;
  content += `## Quantitative Notes\n\n`;
  aptitudeNotes.quantitative.forEach((sec, idx) => {
    content += `### ${idx + 1}. ${sec.title}\n\n`;
    sec.points.forEach((p) => { content += `- ${p}\n`; });
    if (sec.example) content += `\n**Example:** ${sec.example}\n\n`;
    content += `---\n\n`;
  });

  content += `## Logical Notes\n\n`;
  aptitudeNotes.logical.forEach((sec, idx) => {
    content += `### ${idx + 1}. ${sec.title}\n\n`;
    sec.points.forEach((p) => { content += `- ${p}\n`; });
    if (sec.example) content += `\n**Example:** ${sec.example}\n\n`;
    content += `---\n\n`;
  });

  content += `## Verbal Notes\n\n`;
  aptitudeNotes.verbal.forEach((sec, idx) => {
    content += `### ${idx + 1}. ${sec.title}\n\n`;
    sec.points.forEach((p) => { content += `- ${p}\n`; });
    if (sec.example) content += `\n**Example:** ${sec.example}\n\n`;
    content += `---\n\n`;
  });
  content += `*Printable structured notes — ${new Date().toLocaleDateString()}*\n`;
  return content;
}

function generateFormulaMarkdown(): string {
  let content = `# Complete Formula Sheet\n*Generated by Interview Express*\n\n`;
  // Quantitative formulas
  aptitudeFormulas.quantitative.forEach((blk, idx) => {
    content += `## ${idx + 1}. ${blk.heading}\n\n`;
    blk.formulas.forEach((f) => {
      content += `- ${f}\n`;
    });
    content += `\n---\n\n`;
  });
  content += `*ATS-style, clean and printable — ${new Date().toLocaleDateString()}*\n`;
  return content;
}

async function downloadAsPDF(filename: string, markdown: string) {
  const blob = new Blob([markdown], { type: "application/pdf" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

export const AptitudePDFGenerator = {
  async downloadNotes(): Promise<void> {
    const md = generateNotesMarkdown();
    await downloadAsPDF(`Aptitude-Notes-${new Date().toISOString().split("T")[0]}.pdf`, md);
  },
  async downloadFormulaSheet(): Promise<void> {
    const md = generateFormulaMarkdown();
    await downloadAsPDF(`Aptitude-FormulaSheet-${new Date().toISOString().split("T")[0]}.pdf`, md);
  }
};
